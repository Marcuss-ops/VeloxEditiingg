// Command api-schema-gen generates OpenAPI 3.1 components/schemas
// YAML for the inter-service wire-contract types declared in
// internal/apiwire. It is the half-sibling of cmd/api-docs-gen:
// api-docs-gen produces the `paths:` block from a manifest;
// api-schema-gen produces the `components/schemas:` block from
// reflect over canonical Go structs.
//
// Modes:
//
//	api-schema-gen            # write generated schemas to stdout
//	api-schema-gen -out=PATH  # write generated schemas to PATH (file)
//	api-schema-gen -apply     # in-place replace api/openapi.yaml.components.schemas
//	                          # with the generated block (yaml.v3 roundtrip)
//
// Exit codes:
//
//	0 — codegen succeeded
//	1 — apply / I/O error
//	2 — codegen failed (e.g. internal/schemagen returned an error)
package main

import (
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"

	"velox-server/internal/apiwire"
	"velox-server/internal/schemagen"
)

const headerBanner = "# AUTO-GENERATED by cmd/api-schema-gen. DO NOT EDIT.\n" +
	"# Source: DataServer/internal/apiwire (validate:\"...\" tags).\n" +
	"# Re-run `go run ./cmd/api-schema-gen -apply` after editing those types.\n"

func main() {
	var (
		applyFlag = flag.Bool("apply", false, "in-place write api/openapi.yaml.components.schemas")
		specIn    = flag.String("in", "api/openapi.yaml", "input openapi.yaml if -apply is set")
		outFlag   = flag.String("out", "", "output YAML path (default stdout)")
	)
	flag.Parse()

	types := []struct {
		Name  string
		Value any
	}{
		{"SubmitJobRequest", apiwire.SubmitJobRequest{}},
		{"SubmitScene", apiwire.SubmitScene{}},
		{"SubmitClip", apiwire.SubmitClip{}},
		{"SubmitVoiceover", apiwire.SubmitVoiceover{}},
		{"SubmitSubtitles", apiwire.SubmitSubtitles{}},
		{"SubmitLayer", apiwire.SubmitLayer{}},
		{"SubmitDeliveryPlanEntry", apiwire.SubmitDeliveryPlanEntry{}},
		{"SubmitPublishingTarget", apiwire.SubmitPublishingTarget{}},
		{"SubmitManifestRef", apiwire.SubmitManifestRef{}},
		{"SubmitJobBatchRequest", apiwire.SubmitJobBatchRequest{}},
		{"SubmitJobBatchItemResult", apiwire.SubmitJobBatchItemResult{}},
		{"SubmitJobBatchResponse", apiwire.SubmitJobBatchResponse{}},
		{"PublishingCatalogRequest", apiwire.PublishingCatalogRequest{}},
		{"PublishingCatalogCapabilities", apiwire.PublishingCatalogCapabilities{}},
		{"PublishingCatalogChannel", apiwire.PublishingCatalogChannel{}},
		{"PublishingCatalogGroup", apiwire.PublishingCatalogGroup{}},
		{"PublishingCatalogResponse", apiwire.PublishingCatalogResponse{}},
		{"CreatorPushRequest", apiwire.CreatorPushRequest{}},
		{"CreatorPushPayload", apiwire.CreatorPushPayload{}},
		{"CreatorScene", apiwire.CreatorScene{}},
		{"DeliveryPlanEntry", apiwire.DeliveryPlanEntry{}},
		{"CreatorMetadata", apiwire.CreatorMetadata{}},
		{"CreatorAsset", apiwire.CreatorAsset{}},
	}

	// Registry: when nested structs are encountered by name,
	// emit $ref instead of inlining. The registry is the
	// same type set the codegen is producing.
	registry := make([]string, 0, len(types))
	for _, t := range types {
		registry = append(registry, t.Name)
	}

	schemas := map[string]any{}
	for _, t := range types {
		s, err := schemagen.Schema(t.Value, registry...)
		if err != nil {
			fmt.Fprintf(os.Stderr, "FAIL: %s: %v\n", t.Name, err)
			os.Exit(2)
		}
		schemas[t.Name] = s
	}

	keys := []string{}
	for k := range schemas {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	ordered := map[string]any{}
	for _, k := range keys {
		ordered[k] = schemas[k]
	}

	out := map[string]any{
		"components": map[string]any{
			"schemas": ordered,
		},
	}

	data, err := yaml.Marshal(out)
	if err != nil {
		fmt.Fprintf(os.Stderr, "FAIL: marshal: %v\n", err)
		os.Exit(2)
	}
	emitted := append([]byte(headerBanner), data...)

	if *applyFlag {
		if err := applyToSpec(*specIn, ordered); err != nil {
			fmt.Fprintf(os.Stderr, "FAIL: apply: %v\n", err)
			os.Exit(1)
		}
		fmt.Fprintf(os.Stderr, "OK: applied %d generated schemas to %s.components.schemas\n", len(schemas), *specIn)
		return
	}

	if *outFlag != "" {
		if err := os.WriteFile(*outFlag, emitted, 0o644); err != nil {
			fmt.Fprintf(os.Stderr, "FAIL: write %s: %v\n", *outFlag, err)
			os.Exit(1)
		}
		fmt.Fprintf(os.Stderr, "OK: wrote %d generated schemas to %s\n", len(schemas), *outFlag)
		return
	}

	os.Stdout.Write(emitted)
}

// applyToSpec MERGES the generated schemas onto the existing
// api/openapi.yaml.components.schemas block: entries with the
// same NAME as a generated entry are OVERWRITTEN by the
// generated version (canonical); entries with NAME not in the
// generated set are PRESERVED verbatim (subsequent commits
// fold them into internal/apiwire one at a time). The file is
// parsed via yaml.v3 (which strips authoring comments and
// re-orders keys alphabetically — pre-existing byte-drift
// behaviour documented in docs/OPENAPI_MIGRATION.md and
// independent of this commit).
func applyToSpec(path string, schemas map[string]any) error {
	raw, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("read: %w", err)
	}
	var doc map[string]any
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		return fmt.Errorf("parse: %w", err)
	}
	comp, ok := doc["components"].(map[string]any)
	if !ok {
		comp = map[string]any{}
	}
	existingSchemas, _ := comp["schemas"].(map[string]any)
	if existingSchemas == nil {
		existingSchemas = map[string]any{}
	}

	// Keys in alphabetical order for stable diffs across regenerations.
	keys := []string{}
	for k := range schemas {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	overwritten := []string{}
	for _, k := range keys {
		_, had := existingSchemas[k]
		existingSchemas[k] = schemas[k]
		if had {
			overwritten = append(overwritten, k)
		}
	}
	comp["schemas"] = existingSchemas
	doc["components"] = comp
	out, err := yaml.Marshal(doc)
	if err != nil {
		return fmt.Errorf("marshal: %w", err)
	}
	if err := os.WriteFile(path, append([]byte(headerBanner), out...), 0o644); err != nil {
		return fmt.Errorf("write: %w", err)
	}
	sort.Strings(overwritten)
	fmt.Fprintf(os.Stderr, "OK: merged %d generated schemas onto %d existing (overwritten: %s; preserved-untouched: others)\n",
		len(schemas), len(existingSchemas)-len(schemas), strings.Join(overwritten, ", "))
	return nil
}
